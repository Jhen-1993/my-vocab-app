// Build a fast case-insensitive lookup table for rendering, imports, and filters.
var PARTS_OF_SPEECH = Object.create(null);
PARTS_OF_SPEECH_ROWS.forEach(function(row){
  var parts = row.split("|");
  PARTS_OF_SPEECH[parts[0]] = parts[1];
});

// Normalize common user input (e.g. "noun" or "n") to the same compact labels used by filters.
function normalizePartOfSpeech(posText){
  var aliases = {
    "n":"n.", "noun":"n.", "v":"v.", "verb":"v.", "adj":"adj.", "adjective":"adj.",
    "adv":"adv.", "adverb":"adv.", "prep":"prep.", "preposition":"prep.", "conj":"conj.",
    "conjunction":"conj.", "pron":"pron.", "pronoun":"pron.", "quant":"quant.",
    "quantifier":"quant.", "phrasal verb":"phr.v.", "phrasal-verb":"phr.v.", "phr.v":"phr.v."
  };
  return String(posText || "").split(/[／/]/).map(function(part){
    var key = part.trim().toLowerCase();
    return aliases[key] || part.trim();
  }).filter(Boolean).join("／");
}

// Explicit POS on a user-imported card takes priority. Unknown new words remain visibly untagged instead of being guessed.
function getPartOfSpeech(en, explicitPos){
  var normalized = normalizePartOfSpeech(explicitPos);
  var key = String(en || "").trim().toLowerCase().replace(/／/g, "/");
  return normalized || PARTS_OF_SPEECH[key] || "\u672A\u6A19\u8A3B";
}

// Multi-POS entries such as n.?v. should appear in either requested filter.
function hasPartOfSpeech(posText, requestedPos){
  if(requestedPos === "all") return true;
  return String(posText || "").split("\uFF0F").indexOf(requestedPos) !== -1;
}
